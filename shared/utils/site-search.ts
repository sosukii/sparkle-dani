const pageStems = new Map<string, string[]>(
  SITE_PAGES.map((page) => [page.id, [...new Set(page.keywords.flatMap((k) => wordsOf(k)).map(stem))]]),
)

/** Разделы сайта, подходящие под запрос (по словарю ключевых слов), лучшие — первыми. */
export function matchSitePages(query: string, limit = 3): SitePage[] {
  const { groups } = analyzeQuery(query)
  if (groups.length === 0) return []
  const scored = SITE_PAGES.map((page, order) => {
    const keywordStems = pageStems.get(page.id)!
    // Слово запроса подходит, если оно (или его синоним) совпадает с ключевым словом в любую сторону.
    const matched = groups.filter((alternatives) =>
      alternatives.some((s) => keywordStems.some((k) => stemMatches(s, k) || stemMatches(k, s))),
    ).length
    return { page, order, matched }
  }).filter((item) => item.matched > 0 && item.matched >= Math.ceil(groups.length / 2))
  return scored
    .sort((a, b) => b.matched - a.matched || a.order - b.order)
    .slice(0, limit)
    .map((item) => item.page)
}

